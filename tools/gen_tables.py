"""Fixed-point tables for Makkuro37 (no float on the target).  gen_tables.py OUT.h"""
import math
import sys

FS = 44100
CTL = 32                        # control block: samples per control tick


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def expmap(v, lo, hi, n=127):
    return lo * (hi / lo) ** (v / n)


def main(path):
    L = ["/* generated by tools/gen_tables.py */", "#pragma once", "#include <stdint.h>",
         f"#define FS {FS}", f"#define CTL {CTL}", ""]
    L += arr("SINE", "int16_t", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)])
    # phase increment (2^32 = FS) of the top octave, cents 12000..13199 above MIDI 0 (8.1758 Hz)
    L += arr("INC_TOP", "uint32_t",
             [round(440 * 2 ** ((12000 + c) / 1200 - 69 / 12) / FS * 2 ** 32) for c in range(1200)], 8)
    # envelope: attack step per control tick (Q24 full scale), release / decay factor per tick (Q16)
    t = [expmap(v, 0.004, 24.0) for v in range(128)]
    L += arr("ENV_STEP", "uint32_t", [max(1, round((1 << 24) * CTL / (s * FS))) for s in t], 8)
    L += arr("ENV_FALL", "uint16_t", [min(65535, round(65536 * math.exp(-CTL * 5.0 / (s * FS)))) for s in t])
    # LFO / clock phase increment per control tick: A 0.005..2 Hz, B 0.05..40 Hz, pulser 0.1..25 Hz
    for name, lo, hi in (("LFO_A", 0.005, 2.0), ("LFO_B", 0.05, 40.0), ("PULSE", 0.1, 25.0),
                         ("MODR", 0.08, 20.0)):
        L += arr(name, "uint32_t", [round(expmap(v, lo, hi) * CTL / FS * 2 ** 32) for v in range(128)], 8)
    # TPT state-variable filter: g = tan(pi fc / FS), Q16; fc 30 Hz .. 16 kHz over 0..1023
    L += arr("SVF_G", "uint32_t",
             [round(65536 * math.tan(math.pi * expmap(i, 30.0, 16000.0, 1023) / FS)) for i in range(1024)], 8)
    # tanh soft clip over x = -4..4 (513 points), Q15 out
    L += arr("TANH", "int16_t", [round(32767 * math.tanh((i - 256) / 64.0)) for i in range(513)])
    # after Melodee37's PROPHET tables (Kerem Kilic, GPL-3.0): a tanh knee over 0..2 (Q15 in, x 32 a step),
    # four-pole TPT ladder poles G = tan / (1 + tan), Q12, on the filter's cutoff curve
    L += arr("SAT_Q15", "int16_t", [int(32767 * math.tanh(i / 2048 * 2)) for i in range(2049)])
    L += arr("LAD_G", "uint16_t", [round(4096 * (lambda t: t / (1 + t))(math.tan(math.pi * expmap(i, 30.0, 16000.0, 1023) / FS)))
                                    for i in range(1024)])
    # a voice's tone: two one-poles, k = 1 - exp(-2 pi fc / FS), fc 250 Hz .. 18 kHz, Q15
    L += arr("TONE_K", "uint16_t", [round(32767 * (1 - math.exp(-2 * math.pi * expmap(v, 250.0, 18000.0) / FS)))
                                     for v in range(128)])
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"tables: {path}")


if __name__ == "__main__":
    main(sys.argv[1])
